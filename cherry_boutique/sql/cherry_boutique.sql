/*Registrar un pedido y calcular el total*/
CREATE PROCEDURE sp_registrar_pedido(IN p_cliente INT, IN p_metodo INT, IN p_producto INT, IN p_cantidad INT)
BEGIN
  DECLARE v_precio DECIMAL(10,2);
  DECLARE v_exist  INT;
  DECLARE v_pedido INT;

  SELECT PRECIO, EXISTENCIA INTO v_precio, v_exist FROM PRODUCTOS WHERE ID_PRODUCTO = p_producto;

  IF v_exist IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'El producto no existe';
  ELSEIF p_cantidad < 1 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'La cantidad debe ser mayor a cero';
  ELSEIF v_exist < p_cantidad THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Existencia insuficiente';
  ELSE
    INSERT INTO PEDIDOS (FECHA_PEDIDO,HORA_PEDIDO,ESTADO,TOTAL,ID_CLIENTE,ID_METODO)
    VALUES (CURDATE(), CURTIME(), 'En proceso', v_precio * p_cantidad, p_cliente, p_metodo);
    SET v_pedido = LAST_INSERT_ID();
    INSERT INTO DETALLES_PEDIDO (CANTIDAD, ID_PEDIDO, ID_PRODUCTO) VALUES (p_cantidad, v_pedido, p_producto);
  END IF;
END$$

/*Eliminar un pedido junto con sus detalles*/
CREATE PROCEDURE sp_eliminar_pedido(IN p_pedido INT)
BEGIN
  DELETE FROM DETALLES_PEDIDO WHERE ID_PEDIDO = p_pedido;
  DELETE FROM PEDIDOS WHERE ID_PEDIDO = p_pedido;
END$$

/*Pedidos de una clienta con JOIN*/
CREATE PROCEDURE sp_pedidos_cliente(IN p_cliente INT)
BEGIN
  SELECT p.ID_PEDIDO, p.FECHA_PEDIDO, p.ESTADO, p.TOTAL, m.NOMBRE_METODO,
         pr.NOMBRE AS PRODUCTO, d.CANTIDAD
  FROM PEDIDOS p
  JOIN METODO_PAGO m      ON m.ID_METODO    = p.ID_METODO
  JOIN DETALLES_PEDIDO d  ON d.ID_PEDIDO    = p.ID_PEDIDO
  JOIN PRODUCTOS pr       ON pr.ID_PRODUCTO = d.ID_PRODUCTO
  WHERE p.ID_CLIENTE = p_cliente
  ORDER BY p.FECHA_PEDIDO DESC, p.HORA_PEDIDO DESC;
END$$

