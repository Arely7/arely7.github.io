-----------DISPARADORES-----------
/*Al agregar un detalle de pedido se descuenta la existencia del producto*/
CREATE TRIGGER trg_detalle_descuenta_stock AFTER INSERT ON DETALLES_PEDIDO
FOR EACH ROW
    UPDATE PRODUCTOS SET EXISTENCIA = EXISTENCIA - NEW.CANTIDAD WHERE ID_PRODUCTO = NEW.ID_PRODUCTO;

/*Al borrar un detalle se regresa la existencia*/
CREATE TRIGGER trg_detalle_devuelve_stock AFTER DELETE ON DETALLES_PEDIDO
FOR EACH ROW
  UPDATE PRODUCTOS SET EXISTENCIA = EXISTENCIA + OLD.CANTIDAD WHERE ID_PRODUCTO = OLD.ID_PRODUCTO;

/*Producto eliminado*/
CREATE TRIGGER trg_producto_eliminado BEFORE DELETE ON PRODUCTOS
FOR EACH ROW
  INSERT INTO BITACORA (TABLA, ACCION, DETALLE)
  VALUES ('PRODUCTOS','DELETE', CONCAT('Se eliminó el producto ', OLD.ID_PRODUCTO, ' - ', OLD.NOMBRE));

/*Producto modificado*/
CREATE TRIGGER trg_producto_modificado AFTER UPDATE ON PRODUCTOS
FOR EACH ROW
  INSERT INTO BITACORA (TABLA, ACCION, DETALLE)
  VALUES ('PRODUCTOS','UPDATE', CONCAT(NEW.NOMBRE, ': precio ', OLD.PRECIO, ' -> ', NEW.PRECIO, ', existencia ', OLD.EXISTENCIA, ' -> ', NEW.EXISTENCIA));

/*Cliente nuevo*/
CREATE TRIGGER trg_cliente_nuevo AFTER INSERT ON CLIENTES
FOR EACH ROW
  INSERT INTO BITACORA (TABLA, ACCION, DETALLE)
  VALUES ('CLIENTES','INSERT', CONCAT('Nueva clienta: ', NEW.NOMBRE, ' ', NEW.AP_PATERNO));


